class Command(BaseCommand):
    help = 'Створює демо-статті для блогу (автор — перший адміністратор)'

    def handle(self, *args, **options):
        # Паролів у коді немає: адміністратора створюють командою createsuperuser
        admin = User.objects.filter(is_superuser=True).order_by('id').first()
        if not admin:
            raise CommandError('Спочатку створіть адміністратора: python manage.py createsuperuser')

        for data in POSTS:
            category, _ = Category.objects.get_or_create(name=data['category'],
                                                         defaults={'slug': make_slug(data['category'])})
            post, _ = Post.objects.update_or_create(
                slug=make_slug(data['title']),
                defaults={'title': data['title'], 'excerpt': data['excerpt'], 'content': data['content'],
                          'category': category, 'author': admin},
            )
            tags = [Tag.objects.get_or_create(name=name, defaults={'slug': make_slug(name)})[0]
                    for name in data['tags']]
            post.tags.set(tags)

        self.stdout.write(self.style.SUCCESS(
            f'Блог: {Post.objects.count()} статей, {Category.objects.count()} рубрик, {Tag.objects.count()} тегів'))
